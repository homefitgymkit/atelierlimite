function App() {
  const [route, setRoute] = useState("home");
  const [productId, setProductId] = useState("tee");
  const [articleSlug, setArticleSlug] = useState(AL_JOURNAL[0].slug);
  const [joined, setJoined] = useState(() => {
    try {
      return localStorage.getItem("al_private_view") === "1";
    } catch (e) {
      return false;
    }
  });
  function onJoin() {
    setJoined(true);
    try {
      localStorage.setItem("al_private_view", "1");
    } catch (e) {}
  }
  function go(r, arg) {
    if (r === "product" && arg) setProductId(arg);
    if (r === "journal-article") setArticleSlug(arg || AL_JOURNAL[0].slug);
    setRoute(r);
    window.scrollTo({
      top: 0,
      behavior: "auto"
    });
  }
  return React.createElement("div", {
    className: "app-root grain"
  }, React.createElement(Header, {
    route: route,
    go: go
  }), route === "home" && React.createElement(EditionLine, null), route === "home" && React.createElement(Home, {
    go: go,
    joined: joined,
    onJoin: onJoin
  }), route === "product" && React.createElement(Product, {
    go: go,
    productId: productId,
    joined: joined,
    onJoin: onJoin
  }), route === "article" && React.createElement(Article, {
    go: go
  }), route === "about" && React.createElement(AboutPage, {
    go: go
  }), route === "work" && React.createElement(WorkPage, {
    go: go
  }), route === "journal" && React.createElement(JournalIndex, {
    go: go
  }), route === "collection" && React.createElement(CollectionGallery, {
    go: go
  }), route === "journal-article" && React.createElement(JournalArticle, {
    go: go,
    slug: articleSlug
  }), route === "private" && React.createElement(PrivateViewPage, {
    go: go,
    joined: joined,
    onJoin: onJoin
  }), route === "artists" && React.createElement(ArtistsScreen, {
    go: go
  }), route === "archive" && React.createElement(ArchiveScreen, {
    go: go
  }), React.createElement(Footer, {
    go: go
  }));
}
ReactDOM.createRoot(document.getElementById("root")).render(React.createElement(App, null));
